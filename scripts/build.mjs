// Generates themes/Roseate-color-theme.json from src/. Run with `npm run build`.

import { writeFileSync } from 'node:fs';
import colors from '../src/colors.mjs';
import tokenColors from '../src/tokens.mjs';

const theme = {
	name: 'Roseate',
	type: 'dark',
	semanticHighlighting: true,
	colors,
	tokenColors,
};

const header = '// Generated by scripts/build.mjs from src/. Edit those and run `npm run build`.\n';
const out = new URL('../themes/Roseate-color-theme.json', import.meta.url);
writeFileSync(out, header + JSON.stringify(theme, null, '\t') + '\n');
console.log(`Wrote ${Object.keys(colors).length} colors and ${tokenColors.length} token rules`);
